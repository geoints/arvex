/// Константы длительностей анимаций и задержек в приложении.
class AppDurations {
  const AppDurations._();

  static const Duration short = Duration(milliseconds: 200);
  static const Duration medium = Duration(milliseconds: 350);
  static const Duration long = Duration(milliseconds: 500);
  static const Duration splash = Duration(milliseconds: 1650);
  static const Duration pageTransition = Duration(milliseconds: 420);
  static const Duration fadeOut = Duration(milliseconds: 2500);
}
